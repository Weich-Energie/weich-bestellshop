-- 4. Die Formteil-Gruppe der neuen Artikel aus dem GUT-Gegenstueck ableiten,
--    damit die Gegenpruefung aus Einzelaufmassen sie einordnen kann.
with gruppe as (
  select z.rf_artikelnummer,
         min(kl.formteil_system) as system,
         min(kl.dimensionsgruppe) as dimensionsgruppe,
         min(kl.preisklasse) as preisklasse
    from public.shop_gut_rf_zuordnung z
    join public.shop_gut_artikel_klassifikation kl on kl.artikelnummer = z.gut_artikelnummer
   where z.rf_artikelnummer is not null and kl.kategorie = 'formteil'
     and kl.formteil_system is not null and kl.dimensionsgruppe is not null
     and kl.preisklasse is not null
   group by z.rf_artikelnummer
  having count(distinct kl.formteil_system || '|' || kl.dimensionsgruppe
                        || '|' || kl.preisklasse) = 1
)
update public.shop_artikel a
   set formteil_system = gr.system,
       formteil_dimensionsgruppe = gr.dimensionsgruppe,
       formteil_preisklasse = gr.preisklasse,
       updated_at = now()
  from gruppe gr
 where a.artikelnr = gr.rf_artikelnummer
   and not a.formteil_aufmass
   and a.formteil_system is null;

